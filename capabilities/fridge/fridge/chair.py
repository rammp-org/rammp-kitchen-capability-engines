"""The wheelchair and its occupant as collision boxes: the arm's keep-out for every fridge plan and trajectory.

The boxes are the cuRobo planner's own layers for flatbot (drive base, seat, person, floor), generated by RAMMP-CuRobo's
scripts/generate_layers.py and copied into config/chair/ from rammp-deployments
december_2026/config/robots/flatbot/curobo/ (dev at 63e7563, 2026-11-06). The planner does not publish its collision
world over ROS, so the node reads the layer files: `chair_model_dir` points at another directory of them (for example
the robot's own curobo/ directory, bind-mounted), empty is this package's copy. Refresh the copy whenever
rammp-deployments regenerates the layers.

Every box is axis-aligned in arm_mount, the frame the sim plans in, and grown by `padding_m` on every side, as the
planner grows them by its world_padding (0.02). A configuration is in the keep-out when any arm or gripper link touches
a box; arm_base_link is skipped, being bolted to the chair (the layers are carved around it).
"""

from pathlib import Path

import numpy as np
import pybullet as p
import yaml
from capability_engine import sim

PADDING_M = 0.02  # the planner's world_padding: the layers are certified for it
LAYERS = ("layer_mebot_platform.yaml", "layer_mebot_seat.yaml", "layer_mebot_person.yaml", "layer_mebot_floor.yaml")
IGNORED_LINKS = {"arm_base_link"}


def default_dir():
    """This package's copy of the layers: installed (share/fridge/config/chair) or in the source tree."""
    src = Path(__file__).resolve().parent.parent / "config" / "chair"
    if src.is_dir():
        return src
    from ament_index_python.packages import get_package_share_directory

    return Path(get_package_share_directory("fridge")) / "config" / "chair"


def load(directory=None):
    """[(layer/name, centre xyz, size xyz)] of every box in the layer files, unpadded, in arm_mount."""
    directory = Path(directory) if directory else default_dir()
    boxes = []
    for name in LAYERS:
        path = directory / name
        if not path.exists():
            raise FileNotFoundError(f"chair model: no {name} in {directory}")
        data = yaml.safe_load(path.read_text())
        frame = (data.get("meta") or {}).get("frame", "arm_mount")
        if frame != "arm_mount":
            raise ValueError(f"chair model: {path} is in {frame!r}, not arm_mount")
        for o in data["obstacles"]:
            centre, size = np.asarray(o["position"], float), np.asarray(o["dims"], float)
            boxes.append((f"{data['layer']}/{o['name']}", centre, size))
    return boxes


def enable(directory=None, padding_m=PADDING_M):
    """Make the chair model the keep-out (sim.set_keep_out): solve_ik, the plans' gates and self.arm.move_joints all
    refuse a configuration touching it. Returns the boxes."""
    boxes = load(directory)
    bodies = {}  # physics client id -> [(body id, box name)]

    def keep_out(rb, q):
        """Why joints `q` put the arm into the chair model, or None. The arm is left at `q`."""
        c = rb.physics_client_id
        if c not in bodies:
            base = np.asarray(p.getBasePositionAndOrientation(rb.robot_id, physicsClientId=c)[0])
            made = []
            for name, centre, size in boxes:
                half = (size / 2 + padding_m).tolist()
                shape = p.createCollisionShape(p.GEOM_BOX, halfExtents=half, physicsClientId=c)
                body = p.createMultiBody(0, shape, basePosition=(base + centre).tolist(), physicsClientId=c)
                made.append((body, name))
            bodies[c] = made
        for j, jj in enumerate(sim.ARM):
            p.resetJointState(rb.robot_id, jj, float(q[j]), physicsClientId=c)
        worst = None
        for bid, name in bodies[c]:
            for pt in p.getClosestPoints(rb.robot_id, bid, 0.0, physicsClientId=c):
                link = p.getJointInfo(rb.robot_id, pt[3], physicsClientId=c)[12].decode() if pt[3] >= 0 else "base"
                if link in IGNORED_LINKS:
                    continue
                if worst is None or pt[8] < worst[0]:
                    worst = (pt[8], link, name)
        if worst is None:
            return None
        return (
            f"{worst[1]} {-worst[0] * 100:.1f} cm into the wheelchair model ({worst[2]}, padded "
            f"{padding_m * 100:.0f} cm)"
        )

    sim.set_keep_out(keep_out)
    return boxes
